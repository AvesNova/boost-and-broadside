"""Turn the JSON records of torch_bench.py / jax_bench.py into markdown tables.

    python summarize.py results/torch_cpu.json results/jax_cpu.json > results/results.md

Needs only the stdlib. Every number printed is read from a record; nothing is derived except
the ratios and differences that say so.
"""

import json
import sys


def load(paths):
    rows, metas = [], []
    for path in paths:
        with open(path) as handle:
            data = json.load(handle)
        meta = data["meta"]
        metas.append((path, meta))
        for record in data["records"]:
            record["framework"] = meta["framework"]
            record["device"] = meta["device"]
            record["source"] = path.replace("\\", "/").split("/")[-1]
            rows.append(record)
    return rows, metas


def label(r):
    name = {"pytorch": "PyTorch", "jax": "JAX"}[r["framework"]]
    variant = r.get("variant") or r.get("method")
    return f"{name} {variant}"


def table(header, body):
    if not body:
        return "_no records_\n"
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out) + "\n"


def seconds(x):
    return "-" if x is None else (f"{x:.1f}" if x >= 10 else f"{x:.2f}" if x >= 0.1 else f"{x:.4f}")


def ms(x):
    return f"{x:.1f}" if x >= 100 else f"{x:.2f}" if x >= 1 else f"{x:.3f}"


UNIT = {"A": "A policy step", "B": "B game step", "tick": "A+B rollout tick", "C": "C PPO update"}


def size(r):
    if r.get("unit") == "C":
        return f"{r['envs']}x{r['time']}x{r['ships']}"
    return f"E={r['envs']} N={r['ships']}"


def main(paths):
    rows, metas = load(paths)
    of = lambda suite: [r for r in rows if r["suite"] == suite]
    print("# Framework spike results\n")
    print("Generated by `summarize.py` from the JSON records listed below. Times are wall-clock.\n")
    for path, meta in metas:
        m = meta["machine"]
        versions = ", ".join(f"{k} {meta[k]}" for k in ("torch", "jax", "jaxlib", "optax", "numpy") if meta.get(k))
        print(f"- `{path}`: {meta['framework']} on **{meta['device']}**"
              f"{' (' + str(meta.get('gpu')) + ')' if meta.get('gpu') else ''}; {versions}; python {m['python']}; "
              f"CPU: {m.get('lscpu Model name', '?')}, {m.get('cpu_count')} logical CPUs"
              f"{', hypervisor ' + m['lscpu Hypervisor vendor'] if m.get('lscpu Hypervisor vendor') else ''}; "
              f"{m['platform']}")
    errors = of("error")
    if errors:
        print("\n## Failures\n")
        for r in errors:
            print(f"- {r['framework']} {r['device']} `{' '.join(r['argv'])}` exited {r['returncode']}:\n\n```\n{r['stderr_tail'][-1200:]}\n```")

    print("\n## 1. Compile time (seconds; fresh process each)\n")
    print("First call = trace + compile + run. Cold = empty on-disk cache; warm = a second fresh process "
          "reusing the cache the cold run wrote (PyTorch: `TORCHINDUCTOR_CACHE_DIR`; JAX: "
          "`jax_compilation_cache_dir`). Eager PyTorch compiles nothing; its row is the plain first call. "
          "`import` is the time to import the framework, paid in every process and not included in the other columns.\n")
    body = []
    groups = {}
    for r in of("compile"):
        key = (r["device"], r["unit"], r["precision"], label(r), size(r))
        groups.setdefault(key, {})[r["cache"]] = r
    for (device, unit, precision, name, sz), g in groups.items():
        cold, warm = g.get("cold"), g.get("warm")
        body.append([device, UNIT[unit], sz, precision, name,
                     seconds(cold["first_call_s"]) if cold else "-",
                     seconds(warm["first_call_s"]) if warm else "-",
                     seconds(cold["second_call_s"]) if cold else "-",
                     seconds(cold["import_s"]) if cold else "-"])
    print(table(["device", "unit", "size", "precision", "variant", "cold first call", "warm first call",
                 "second call (cold process)", "import"], body))

    print("## 2. Steady step time (milliseconds per call, after warm-up)\n")
    print("Median over the timed repeats, with the interquartile range in brackets; each repeat is a loop of calls "
          "lasting about `--budget` seconds.\n")
    body = [[r["device"], UNIT[r["unit"]], size(r), r["precision"], label(r),
             f"{ms(r['median_ms'])} ({ms(r['q1_ms'])}-{ms(r['q3_ms'])})", r["repeats"], r["iterations"]]
            for r in sorted(of("steady"), key=lambda r: (r["device"], "AB tC".index(r["unit"][0]), r["envs"], r["precision"]))]
    print(table(["device", "unit", "size", "precision", "variant", "median ms (q1-q3)", "repeats", "calls per repeat"], body))

    print("## 3. One model, many team sizes (rollout tick)\n")
    print("One process per method: compile at N = 10, then meet N = 20, 40, 100, then N = 10 again. "
          "`first result` is the first call at that size (it includes any recompile); `graphs` is how many new "
          "compiled graphs that size cost (PyTorch: TorchDynamo's unique-graph counter; JAX: the jit cache size). "
          "Padded methods run every size in `slots` = 100 ship slots with the key mask. PyTorch caches were empty at the start.\n")
    body = []
    for r in of("sizes"):
        if "error" in r and "median_ms" not in r:
            body.append([r["device"], label(r), r["envs"], r["ships"], r["slots"], "FAILED", "-", "-", r["error"][:300].replace("\n", " ")])
            continue
        body.append([r["device"], label(r), r["envs"], r["ships"], r["slots"], seconds(r["first_call_s"]),
                     seconds(r["second_call_s"]), f"{ms(r['median_ms'])} ({ms(r['q1_ms'])}-{ms(r['q3_ms'])})",
                     f"{r['graphs_compiled_here']} (total {r['graphs_compiled_total']})"])
    print(table(["device", "method", "E", "N", "slots", "first result s", "second call s", "steady median ms (q1-q3)", "graphs"], body))

    print("## 4. Whole rollout loop (T ticks, actions sampled on device, actions and log-probs kept)\n")
    body = [[r["device"], label(r), r["envs"], r["ships"], r["ticks"], seconds(r["first_rollout_s"]),
             f"{ms(r['rollout']['median_ms'])} ({ms(r['rollout']['q1_ms'])}-{ms(r['rollout']['q3_ms'])})",
             f"{r['ticks_per_s']:.0f}", f"{r['env_ticks_per_s']:.0f}"]
            for r in sorted(of("loop"), key=lambda r: (r["device"], r["envs"]))]
    print(table(["device", "variant", "E", "N", "T", "first rollout s (incl. compile)", "rollout median ms (q1-q3)",
                 "ticks/s", "env-ticks/s"], body))

    print("## 5. Batch-size-1 latency: one game tick + two policy forwards (milliseconds)\n")
    print("Single process, E = 1, every tick timed individually after warm-up. Threads: `default` = framework default; "
          "`1` = `torch.set_num_threads(1)` / XLA flags asking for no intra-op thread pool; `pin` = the whole process "
          "pinned to one core with `os.sched_setaffinity`.\n")
    body = [[r["device"], r["ships"], label(r), r["threads"], ms(r["p50_ms"]), ms(r["p99_ms"]), ms(r["max_ms"]), r["ticks"], r["source"]]
            for r in sorted(of("latency"), key=lambda r: (r["device"], int(r["ships"]), r["threads"], label(r), r["source"]))]
    print(table(["device", "N", "variant", "threads", "p50", "p99", "max", "ticks", "record file"], body))

    print("## 6. Operation counts (context)\n")
    print("PyTorch: operations dispatched per call when uncompiled (TorchDispatchMode counter; view ops launch no kernel). "
          "JAX: primitives in the traced program before XLA fuses them; they are not dispatched one by one at run time, "
          "so the two columns are not the same kind of number.\n")
    ops = {}
    for r in of("ops"):
        ops.setdefault((r["what"], r["ships"]), {}).update(r)
    body = [[what, ships, r.get("compute_ops", "-"), r.get("view_ops", "-"), r.get("jaxpr_primitives", "-")]
            for (what, ships), r in ops.items()]
    print(table(["what", "N", "PyTorch compute ops", "PyTorch view ops", "JAX traced primitives"], body))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
