"""Tables for the laptop run (run_laptop.sh): results/laptop/*.json -> markdown on stdout.

    python aggregate.py results/laptop > results/results_laptop.md

Suites run once per repeat (compile, sizes, latency) are shown as the median over repeats with
the interquartile range across repeats in brackets and the number of repeats. Suites that repeat
inside one invocation (steady, loop) show that invocation's median and quartiles over its 7
timed repeats. Stdlib only; every number is read from a record or is a median/quartile of them.
"""

import collections
import glob
import json
import os
import statistics
import sys

NAME = {"pytorch": "PyTorch", "jax": "JAX"}


def quartiles(values):
    values = sorted(values)
    if len(values) == 1:
        return values[0], values[0], values[0]
    q = statistics.quantiles(values, n=4, method="inclusive")
    return q[0], statistics.median(values), q[2]


def fmt(x):
    if x is None:
        return "-"
    if abs(x) >= 100:
        return f"{x:.0f}"
    if abs(x) >= 10:
        return f"{x:.1f}"
    if abs(x) >= 1:
        return f"{x:.2f}"
    return f"{x:.3g}"


def spread(values):
    values = [v for v in values if v is not None]
    if not values:
        return "-"
    q1, median, q3 = quartiles(values)
    if len(values) == 1:
        return f"{fmt(median)} (n=1)"
    return f"{fmt(median)} [{fmt(q1)}-{fmt(q3)}] (n={len(values)})"


def table(header, rows):
    if not rows:
        return "_no records_\n"
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def load(folder):
    files = {}
    for path in sorted(glob.glob(os.path.join(folder, "*.json"))):
        with open(path) as handle:
            data = json.load(handle)
        name = os.path.basename(path)[:-5]
        meta = data["meta"]
        for index, record in enumerate(data["records"]):
            record.update(
                framework=meta["framework"], device=meta["device"], file=name, index=index
            )
        files[name] = data
    return files


def records(files, suite, prefix=None):
    out = []
    for name, data in files.items():
        if prefix and not name.startswith(prefix):
            continue
        out += [r for r in data["records"] if r["suite"] == suite]
    return out


def main(folder):
    files = load(folder)
    print("# Framework spike: laptop results (RTX 4070 Laptop GPU, native Ubuntu)\n")
    print(
        f"Generated by `aggregate.py` from {len(files)} JSON records in `{folder}/` "
        "(written by `run_laptop.sh`). Wall-clock times. `median [q1-q3] (n=repeats)`.\n"
    )

    # ---- environment
    print("## Environment\n")
    seen = set()
    for name, data in files.items():
        m = data["meta"]
        key = (
            m["framework"],
            m["device"],
            m.get("float32_matmul_precision"),
            m.get("default_matmul_precision"),
        )
        if key in seen:
            continue
        seen.add(key)
        if m["framework"] == "pytorch":
            what = (
                f"torch {m['torch']}, CUDA runtime {m.get('cuda_runtime')}, float32 matmul precision "
                f"`{m.get('float32_matmul_precision')}`"
            )
        else:
            what = (
                f"jax {m['jax']}, jaxlib {m['jaxlib']}, optax {m['optax']}, default matmul precision "
                f"`{m.get('default_matmul_precision')}`"
            )
        mach = m["machine"]
        print(
            f"- {NAME[m['framework']]} on **{m['device']}** (e.g. `{name}`): {what}; numpy {m['numpy']}; "
            f"python {mach['python']}; GPU {m.get('gpu') or m.get('devices')}; CPU {mach.get('lscpu Model name')}, "
            f"{mach.get('lscpu CPU(s)')} logical; {mach['platform']}"
        )
    print()

    # ---- machine load
    loads, temps, clocks, powers = [], [], [], []
    for name, data in files.items():
        for r in data["records"]:
            for key in ("load_before", "load_after"):
                snap = r.get(key)
                if not snap:
                    continue
                loads.append(snap["loadavg"][0])
                gpu = snap.get("gpu", {})
                for target, field, unit in (
                    (temps, "temperature.gpu", ""),
                    (clocks, "clocks.sm", " MHz"),
                    (powers, "enforced.power.limit", " W"),
                ):
                    try:
                        target.append(float(gpu[field].replace(unit, "").strip()))
                    except (KeyError, ValueError):
                        pass
    if loads:
        print("## Machine load (snapshots before and after every child process)\n")
        print(f"- 1-minute load average: {spread(loads)}; max {fmt(max(loads))}")
        if temps:
            print(f"- GPU temperature C: {spread(temps)}; max {fmt(max(temps))}")
        if powers:
            print(f"- GPU enforced power limit W: {sorted(set(powers))}")
        print()

    # ---- failures
    errors = [r for d in files.values() for r in d["records"] if r["suite"] == "error"]
    print("## Failures\n")
    if not errors:
        print("None: no child process failed.\n")
    for r in errors:
        tail = r["stderr_tail"].strip().splitlines()
        print(
            f"- `{r['file']}`: `{' '.join(r['argv'][:12])}` exited {r['returncode']}: `{tail[-1] if tail else ''}`"
        )
    print()

    # ---- compile
    print(
        "## 1. Compile time, GPU (seconds, fresh process, first call = trace + compile + one run)\n"
    )
    print(
        "Cold: empty on-disk cache; warm: a second fresh process reusing it. `graphs` = compiled graphs "
        "recorded on the first call (PyTorch only; more than 1 means a graph break or recompile). "
        "Import time is paid by every process on top.\n"
    )
    groups = collections.defaultdict(list)
    for r in records(files, "compile"):
        groups[(r["unit"], r["precision"], r["framework"], r["variant"], r["envs"])].append(r)
    rows = []
    for (unit, precision, framework, variant, envs), rs in sorted(groups.items()):
        cold = [r for r in rs if r.get("cache") == "cold"]
        warm = [r for r in rs if r.get("cache") == "warm"]
        graphs = sorted(
            {r.get("graphs_compiled") for r in rs if r.get("graphs_compiled") is not None}
        )
        rows.append(
            [
                unit,
                f"E={envs}" if unit != "C" else "16x128x10",
                precision,
                f"{NAME[framework]} {variant}",
                spread([r["first_call_s"] for r in cold]),
                spread([r["first_call_s"] for r in warm]) if warm else "-",
                spread([r["second_call_s"] for r in cold]),
                spread([r["import_s"] for r in rs]),
                ",".join(map(str, graphs)) or "-",
            ]
        )
    print(
        table(
            [
                "unit",
                "size",
                "precision",
                "variant",
                "cold first call s",
                "warm first call s",
                "second call s (cold process)",
                "import s",
                "graphs",
            ],
            rows,
        )
    )

    # ---- steady
    for suffix, title in (("", "matched float32 (both `highest`)"), ("_tf32", "both on TF32")):
        print(f"## 2{'b' if suffix else ''}. Steady step time, GPU, {title} (ms per call)\n")
        print("One invocation; median [q1-q3] over its 7 timed repeats of about 1 s each.\n")
        rows = []
        for r in sorted(
            (
                r
                for name, d in files.items()
                if name in (f"torch_gpu_steady{suffix}", f"jax_gpu_steady{suffix}")
                for r in d["records"]
                if r["suite"] == "steady"
            ),
            key=lambda r: (r["unit"], r["envs"], r["precision"], r["framework"], r["variant"]),
        ):
            size = f"E={r['envs']} N={r['ships']}" if r["unit"] != "C" else "16x128x10"
            rows.append(
                [
                    r["unit"],
                    size,
                    r["precision"],
                    f"{NAME[r['framework']]} {r['variant']}",
                    f"{fmt(r['median_ms'])} [{fmt(r['q1_ms'])}-{fmt(r['q3_ms'])}]",
                    r.get("graphs_compiled", "-"),
                ]
            )
        print(table(["unit", "size", "precision", "variant", "median ms [q1-q3]", "graphs"], rows))

    # ---- sizes
    print("## 3. One model, many team sizes, GPU (rollout tick, E = size-test envs)\n")
    print(
        "Each repeat is one fresh process (empty caches) that compiles at N = 10 (5v5), then meets "
        "N = 20, 40, 100 (10v10, 20v20, 50v50), then N = 10 again. `first result` includes any recompile.\n"
    )
    groups = collections.defaultdict(list)
    for r in records(files, "sizes"):
        groups[(r["framework"], r["method"], r["index"])].append(r)
    rows = []
    for (framework, method, index), rs in sorted(groups.items()):
        r0 = rs[0]
        graphs = sorted({r["graphs_compiled_here"] for r in rs})
        rows.append(
            [
                f"{NAME[framework]} {method}",
                r0["envs"],
                r0["ships"],
                r0["slots"],
                spread([r["first_call_s"] for r in rs]),
                spread([r["median_ms"] for r in rs]),
                ",".join(map(str, graphs)),
            ]
        )
    print(table(["method", "E", "N", "slots", "first result s", "steady ms", "new graphs"], rows))

    # ---- loop
    for suffix, title in (("", "matched float32"), ("_tf32", "both on TF32")):
        print(f"## 4{'b' if suffix else ''}. Whole rollout loop, GPU, {title} (T = 128 ticks)\n")
        rows = []
        for r in sorted(
            (
                r
                for name, d in files.items()
                if name in (f"torch_gpu_loop{suffix}", f"jax_gpu_loop{suffix}")
                for r in d["records"]
                if r["suite"] == "loop"
            ),
            key=lambda r: (r["envs"], r["framework"], r["variant"]),
        ):
            ro = r["rollout"]
            rows.append(
                [
                    f"{NAME[r['framework']]} {r['variant']}",
                    r["envs"],
                    r["ships"],
                    fmt(r["first_rollout_s"]),
                    f"{fmt(ro['median_ms'])} [{fmt(ro['q1_ms'])}-{fmt(ro['q3_ms'])}]",
                    fmt(r["ticks_per_s"]),
                    fmt(r["env_ticks_per_s"]),
                ]
            )
        print(
            table(
                [
                    "variant",
                    "E",
                    "N",
                    "first rollout s",
                    "rollout ms [q1-q3]",
                    "ticks/s",
                    "env-ticks/s",
                ],
                rows,
            )
        )

    # ---- latency
    print("## 5. Batch-size-1 latency: one game tick + two policy forwards (ms)\n")
    print(
        "Each repeat: one fresh process, 300 warm-up ticks, 3,000 timed ticks. p50/p99/max are per "
        "repeat; shown as median [q1-q3] over repeats, plus the worst max of any repeat. Budget: p99 <= 16 ms, "
        "worst frame <= 33 ms.\n"
    )
    groups = collections.defaultdict(list)
    for r in records(files, "latency"):
        groups[(r["device"], r["ships"], r["framework"], r["variant"], r["threads"])].append(r)
    rows = []
    for (device, ships, framework, variant, threads), rs in sorted(groups.items()):
        worst_p99, worst_max = max(r["p99_ms"] for r in rs), max(r["max_ms"] for r in rs)
        verdict = "meets" if worst_p99 <= 16 and worst_max <= 33 else "**fails**"
        rows.append(
            [
                device,
                f"{ships // 2}v{ships // 2}",
                f"{NAME[framework]} {variant}",
                threads,
                spread([r["p50_ms"] for r in rs]),
                spread([r["p99_ms"] for r in rs]),
                fmt(worst_p99),
                fmt(worst_max),
                verdict,
            ]
        )
    print(
        table(
            [
                "device",
                "size",
                "variant",
                "threads",
                "p50",
                "p99",
                "worst p99",
                "worst max",
                "budget",
            ],
            rows,
        )
    )

    # ---- ops
    print("## 6. Operation counts (context)\n")
    rows = []
    ops = collections.defaultdict(dict)
    for r in records(files, "ops"):
        ops[r["what"]][r["framework"]] = r
    for what, by in ops.items():
        t, j = by.get("pytorch", {}), by.get("jax", {})
        rows.append(
            [
                what,
                t.get("compute_ops", "-"),
                t.get("view_ops", "-"),
                j.get("jaxpr_primitives", "-"),
            ]
        )
    print(
        table(
            ["what (N = 10)", "PyTorch compute ops", "PyTorch view ops", "JAX traced primitives"],
            rows,
        )
    )


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results/laptop")
